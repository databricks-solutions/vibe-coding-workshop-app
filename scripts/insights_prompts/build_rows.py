def edit(text: str, old: str, new: str) -> str:
    n = text.count(old)
    if n != 1:
        raise SystemExit(f"expected exactly one match, found {n}: {old[:90]!r}")
    return text.replace(old, new)


def source(tag: str, assistant: str = "__default__") -> Dict[str, Any]:
    row = latest(tag, assistant)
    if not row:
        raise SystemExit(f"missing source row {tag}/{assistant}")
    return row


