def build() -> List[Dict[str, Any]]:
    """Each tag gets a Default row (shared fields + the same prompt) and a genie-code fork."""
    out: List[Dict[str, Any]] = []
    for make in BUILDERS:
        for spec in make():
            base = {
                "section_tag": spec["section_tag"],
                "input_template": spec["input_template"],
                "system_prompt": "",
                "bypass_llm": True,
            }
            out.append({**base, "coding_assistant": "__default__", **{k: spec[k] for k in (
                "section_title", "section_description", "order_number", "how_to_apply", "expected_output")}})
            out.append({**base, "coding_assistant": "genie-code"})
    return out


def _lit(v: Any) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        return str(v)
    return "'" + str(v).replace("'", "''") + "'"


def seed_block(rows: List[Dict[str, Any]]) -> str:
    parts = [BEGIN, "-- Insights view only (section tags insights_*). No Technical step uses these tags.", ""]
    for r in rows:
        if r["coding_assistant"] == "__default__":
            iid = next(DEFAULT_IDS)
            parts.append(f"-- {r['section_tag']} (default)")
            parts.append("INSERT INTO ${catalog}.${schema}.section_input_prompts")
            parts.append("(input_id, section_tag, input_template, system_prompt, section_title, section_description, order_number, how_to_apply, expected_output, bypass_llm, version, is_active, inserted_at, updated_at, created_by)")
            parts.append("VALUES")
            parts.append("(" + ", ".join([
                str(iid), _lit(r["section_tag"]), _lit(r["input_template"]), _lit(r["system_prompt"]),
                _lit(r["section_title"]), _lit(r["section_description"]), _lit(r["order_number"]),
                _lit(r["how_to_apply"]), _lit(r["expected_output"]), _lit(r["bypass_llm"]),
                "1, true, current_timestamp(), current_timestamp(), current_user()",
            ]) + ");")
        else:
            iid = next(FORK_IDS)
            parts.append(f"-- {r['section_tag']} (genie-code fork)")
            parts.append("INSERT INTO ${catalog}.${schema}.section_input_prompts")
            parts.append("(input_id, section_tag, coding_assistant, input_template, system_prompt, bypass_llm, version, is_active, inserted_at, updated_at, created_by)")
            parts.append("VALUES")
            parts.append("(" + ", ".join([
                str(iid), _lit(r["section_tag"]), _lit(r["coding_assistant"]), _lit(r["input_template"]),
                _lit(r["system_prompt"]), _lit(r["bypass_llm"]),
                "1, true, current_timestamp(), current_timestamp(), current_user()",
            ]) + ");")
        parts.append("")
    parts.append(END)
    return "\n".join(parts) + "\n"


def with_block(seed_text: str, block: str) -> str:
    if BEGIN in seed_text:
        head, rest = seed_text.split(BEGIN, 1)
        _, tail = rest.split(END, 1)
        return head.rstrip("\n") + "\n\n" + block + tail.lstrip("\n")
    return seed_text.rstrip("\n") + "\n\n" + block


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    # Sources must come from the seed without our own block, so a rebuild is stable.
    rows = build()
    rows_text = json.dumps(rows, indent=2, ensure_ascii=False) + "\n"
    seed_text = SEED.read_text()
    new_seed = with_block(seed_text, seed_block(rows))
    if args.check:
        stale = []
        if not ROWS_JSON.exists() or ROWS_JSON.read_text() != rows_text:
            stale.append(str(ROWS_JSON))
        if new_seed != seed_text:
            stale.append(str(SEED))
        if stale:
            print("out of date:", *stale, sep="\n  ")
            return 1
        print("up to date")
        return 0
    ROWS_JSON.write_text(rows_text)
    SEED.write_text(new_seed)
    print(f"wrote {len(rows)} rows to {ROWS_JSON.name} and the seed block")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
